from datetime import UTC, datetime
from enum import StrEnum

from sqlalchemy import Computed, DateTime, String, func
from sqlalchemy.orm import mapped_column


class Role(StrEnum):
    ADMIN = "ADMIN"
    MANAGER = "MANAGER"
    WORKER = "WORKER"
    CUSTOMER = "CUSTOMER"


class UserStatus(StrEnum):
    PENDING = "PENDING"
    ACTIVE = "ACTIVE"
    REJECTED = "REJECTED"
    BLOCKED = "BLOCKED"


class DeviceStatus(StrEnum):
    PENDING = "PENDING"
    APPROVED = "APPROVED"
    REVOKED = "REVOKED"


class OrderStatus(StrEnum):
    PENDING = "PENDING"
    APPROVED = "APPROVED"
    REJECTED = "REJECTED"
    SHIPPED = "SHIPPED"
    CANCELLED = "CANCELLED"


class MovementType(StrEnum):
    IN = "IN"
    OUT = "OUT"


class TransactionType(StrEnum):
    TOPUP = "TOPUP"
    PAYMENT = "PAYMENT"
    REFUND = "REFUND"


STAFF_ROLES = (Role.ADMIN, Role.MANAGER, Role.WORKER)


def in_check(column: str, enum: type[StrEnum]) -> str:
    """SQL text for a CHECK constraint like: role IN ('ADMIN', 'MANAGER')."""
    values = ", ".join(f"'{v.value}'" for v in enum)
    return f"{column} IN ({values})"


def code_column(prefix: str, digits: int):
    """Human-readable code (P001, O0001...) generated by PostgreSQL from the integer id.

    It is a STORED generated column, so two users saving at the same time can never get the same code.
    """
    expr = f"'{prefix}' || lpad(id::text, greatest({digits}, length(id::text)), '0')"
    return mapped_column(String(20), Computed(expr, persisted=True), unique=True)


def created_at_column():
    return mapped_column(DateTime(timezone=True), server_default=func.now(), nullable=False)


def utcnow() -> datetime:
    return datetime.now(UTC)
