"""Builds the translation dictionaries from the text tables in this folder.

i18n/mobile.txt            -> mobile/app/src/main/java/kz/keyfive/staff/i18n/Ru.kt and Kk.kt
i18n/mobile.txt + web.txt  -> frontend/src/i18n/ru.ts and kk.ts (the website reuses the app's texts)

A table is blocks of three lines (English key / Russian / Kazakh) separated by an empty line; lines starting with
"#" are comments. Run from the repository root:  python i18n/build.py
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
HERE = ROOT / 'i18n'


def read_table(path: pathlib.Path) -> dict[str, tuple[str, str]]:
    lines = [l for l in path.read_text(encoding='utf-8').splitlines() if not l.startswith('#')]
    table: dict[str, tuple[str, str]] = {}
    block: list[str] = []
    for line in lines + ['']:
        if line.strip():
            block.append(line)
            continue
        if not block:
            continue
        if len(block) != 3:
            sys.exit(f'{path.name}: a block must have 3 lines (en / ru / kk), got {block}')
        en, ru, kk = block
        if en in table and table[en] != (ru, kk):
            sys.exit(f'{path.name}: "{en}" is translated twice in different ways')
        for text in (ru, kk):
            for i in range(10):
                if (f'{{{i}}}' in en) != (f'{{{i}}}' in text):
                    sys.exit(f'{path.name}: "{en}" and "{text}" use different placeholders')
        table[en] = (ru, kk)
        block = []
    return table


def kotlin(value: str) -> str:
    return '"' + value.replace('\\', '\\\\').replace('"', '\\"').replace('$', '\\$') + '"'


def write_kotlin(table: dict[str, tuple[str, str]]) -> None:
    out = ROOT / 'mobile/app/src/main/java/kz/keyfive/staff/i18n'
    for name, const, index in (('Ru', 'RU_TEXT', 0), ('Kk', 'KK_TEXT', 1)):
        rows = '\n'.join(f'    {kotlin(en)} to {kotlin(pair[index])},' for en, pair in table.items())
        (out / f'{name}.kt').write_text(
            'package kz.keyfive.staff.i18n\n\n'
            '// Generated by i18n/build.py from i18n/mobile.txt. Edit the table, not this file.\n'
            f'val {const}: Map<String, String> = mapOf(\n{rows}\n)\n',
            encoding='utf-8', newline='\n')


def ts(value: str) -> str:
    return "'" + value.replace('\\', '\\\\').replace("'", "\\'") + "'"


def write_typescript(table: dict[str, tuple[str, str]]) -> None:
    out = ROOT / 'frontend/src/i18n'
    for name, const, index in (('ru', 'RU', 0), ('kk', 'KK', 1)):
        rows = '\n'.join(f'  {ts(en)}: {ts(pair[index])},' for en, pair in table.items())
        (out / f'{name}.ts').write_text(
            '// Generated by i18n/build.py from i18n/mobile.txt and i18n/web.txt. Edit the tables, not this file.\n'
            f'export const {const}: Record<string, string> = {{\n{rows}\n}}\n',
            encoding='utf-8', newline='\n')


if __name__ == '__main__':
    mobile = read_table(HERE / 'mobile.txt')
    web_only = read_table(HERE / 'web.txt')
    for en in web_only.keys() & mobile.keys():
        if web_only[en] != mobile[en]:
            sys.exit(f'"{en}" is in mobile.txt and web.txt with different translations: keep one')
    write_kotlin(mobile)
    write_typescript({**mobile, **web_only})
    print(f'mobile: {len(mobile)} texts, website: {len({**mobile, **web_only})} texts')
