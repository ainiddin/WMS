-- =====================================================================
-- 04_transaction.sql : recording a stock movement as ONE transaction
-- Step 1: INSERT the movement.  Step 2: UPDATE the product quantity.
-- If step 2 fails, step 1 is undone (ROLLBACK) — all or nothing.
-- =====================================================================

CREATE OR REPLACE FUNCTION record_movement(
    p_product_id  CHAR(4),
    p_employee_id CHAR(4),
    p_type        VARCHAR(3),
    p_quantity    INT
) RETURNS CHAR(5)
LANGUAGE plpgsql
SECURITY DEFINER            -- runs with the owner's rights: workers do NOT need UPDATE on products
SET search_path = public
AS $$
DECLARE
    v_id    CHAR(5);
    v_rows  INT;
BEGIN
    -- only active products and employees may be used
    IF NOT EXISTS (SELECT 1 FROM products  WHERE product_id  = p_product_id  AND is_active) THEN
        RAISE EXCEPTION 'Product % does not exist or is archived', p_product_id;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM employees WHERE employee_id = p_employee_id AND is_active) THEN
        RAISE EXCEPTION 'Employee % does not exist or is inactive', p_employee_id;
    END IF;

    -- step 1: save the movement (ID is generated by the system)
    v_id := 'M' || LPAD(nextval('movement_seq')::text, 4, '0');
    INSERT INTO stock_movements (movement_id, product_id, employee_id, movement_type, quantity)
    VALUES (v_id, p_product_id, p_employee_id, p_type, p_quantity);

    -- step 2: change the stock
    UPDATE products
    SET quantity     = quantity + CASE WHEN p_type = 'IN' THEN p_quantity ELSE -p_quantity END,
        last_updated = CURRENT_TIMESTAMP
    WHERE product_id = p_product_id
      AND (p_type = 'IN' OR quantity >= p_quantity);

    GET DIAGNOSTICS v_rows = ROW_COUNT;
    IF v_rows <> 1 THEN
        -- raising an error cancels the whole call, including the INSERT above
        RAISE EXCEPTION 'Not enough stock of % — movement cancelled', p_product_id;
    END IF;

    RETURN v_id;
END;
$$;

